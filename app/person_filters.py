"""
Фильтр ложных срабатываний PERSON (этап 2 плана улучшений).

Зачем. На данных чужого домена сервис ставил маску <PERSON> на слова, которые
именами не являются: «запахом», «гражданине», «Страховой», «мокрого дерева»,
«г . Москва», «Таганский» (район), «Тульской» (область). 92 % таких ошибок
даёт наша модель ruBERT, остальные — встроенный в presidio spaCy. Поэтому
фильтр стоит ПОСЛЕ обоих источников, в app.anonymizer.analyze_text, а не внутри
распознавателя модели.

Пять правил. Спан PERSON отбрасывается, если:
  F1  в нём нет ни одной буквы;
  F2  это одно короткое слово (до 3 букв), которое морфология не знает как имя,
      фамилию или отчество: «Нет», «Оф», «ВУ», «физ»;
  F3  это одно словарное нарицательное слово, не являющееся именем:
      «запахом», «гражданине», «Страховой»;
  F4  все слова спана — такие нарицательные: «мокрого дерева»;
  F5  рядом стоит адресный маркер: «г.», «ул.», «район», «области», «улица»…
      («г . Москва», «Таганский район», «Тульской области»).

Защита от потери настоящих имён:
  * слово, у которого есть разбор как личное имя (Name), не трогается никогда;
    разбор как фамилия/отчество защищает, если его балл не ниже NAME_MIN;
  * инициал с точкой в спане («А. Белых») отключает морфологические правила;
  * одиночное слово вплотную к имени/отчеству/фамилии тоже не выбрасывается: это
    часть ФИО, найденного моделью не целиком («Феодосию ВИКТОРОВИЧУ Самбуку»);
  * слово с типичным окончанием фамилии (-ов, -ова, -ин, -ский, -енко, -ук, -ян,
    -ых, -ич…) не трогается, даже если морфология знает его как нарицательное:
    «Орехова», «Головнёва», «чернявский»;
  * однобуквенные адресные сокращения («г.», «с.», «д.») учитываются только
    строчными — заглавная «С.» это инициал, а не «село».

Пороги подобраны перебором на dev-наборах (правило П1 плана), модель при этом
прогонялась один раз, спаны кэшировались. На dev_rmr фильтр снимает 293 из 544
ложных ФИО, на dev_v2 — 33 из 44; ни одно настоящее имя не теряет полного
маскирования ни на одном наборе (допуск плана — не больше 1 п.п.).

Морфология — pymorphy3. Новой зависимости это не добавляет: лемматизатор модели
spaCy ru_core_news_lg работает на нём же и загружен в сервисе всегда.
"""
import re
from functools import lru_cache

import pymorphy3

_MORPH = None
_NAME_TAGS = {"Name", "Surn", "Patr"}
_PROPER_TAGS = {"Name", "Surn", "Patr", "Geox", "Orgn", "Trad"}
_WORD = re.compile(r"[A-Za-zА-Яа-яЁё]+")
_INITIAL = re.compile(r"(?<![A-Za-zА-Яа-яЁё])[A-ZА-ЯЁ]\s?\.")

# Пороги подобраны перебором на dev-наборах (правило П1 плана): при нулевой потере
# доли полностью замаскированных имён — максимум снятых ложных ФИО. Баллы разборов
# pymorphy СУММИРУЮТСЯ по виду: у прилагательного «мокрого» три разбора по 0,33,
# и сравнение одного лучшего разбора с порогом пропускало такие слова.
NAME_MIN = 0.35     # суммарный балл разборов как фамилия/отчество, при котором слово защищено
COMMON_MIN = 0.5    # суммарный балл словарных нарицательных разборов — слово «нарицательное»
# Перебор включал вариант, где окончание фамилии перестаёт защищать слово при сильном
# нарицательном разборе: он снимал на 47 ложных масок больше на dev_rmr, но терял 3
# настоящих имени (0,9 п.п. — у границы допуска). Выбрана защита без исключений:
# лишняя маска безопаснее утечки имени.

# окончания фамилий в начальной форме и в косвенных падежах: «Орехова», «Ореховой»,
# «Ковальского». Слово с таким окончанием морфологическими правилами не выбрасывается.
_SURNAME_SUFFIX = re.compile(
    r"(?:(?:ов|ев|ёв|ин|ын)(?:а|у|ым|ой|ою|е|ы|ых)?|(?:ск|цк)(?:ий|ая|ого|ому|им|ом|ой|ую|ие|их)|"
    r"енко|ук|юк|ян|ых|их|(?:ович|евич|овн|евн)\w*)$", re.I)

# адресный маркер СЛЕВА от спана
_ABBR1_BEFORE = re.compile(r"\b[гсдш]\s*\.\s*$")                         # только строчные
_ABBRN_BEFORE = re.compile(r"\b(?:гор|ул|пр|просп|пер|пл|наб|бул|обл|пос|пгт|мкр)\s*\.\s*$", re.I)
_WORD_BEFORE = re.compile(
    r"\b(?:р-н|б-р|город[а-я]*|улиц[а-я]*|проспект[а-я]*|переул[а-я]*|район[а-я]*|"
    r"област[а-я]*|кра[йяею]|посёл[а-я]*|посел[а-я]*|село|деревн[а-я]*|бульвар[а-я]*|"
    r"шоссе|набережн[а-я]*|площад[а-я]*|станци[а-я]*)\s*$", re.I)
# адресный маркер ВНУТРИ спана, в самом его начале: «г . Москва», «бул . Космонавтов»
_ABBR1_START = re.compile(r"^\s*[гсдш]\s*\.")
_ABBRN_START = re.compile(r"^\s*(?:гор|ул|пр|просп|пер|пл|наб|бул|обл|пос|пгт|мкр)\s*\.", re.I)
# адресный маркер СПРАВА от спана
_AFTER = re.compile(
    r"^\s*(?:област[а-я]*|обл\b|кра[йяею]\b|район[а-я]*|р-н|улиц[а-я]*|ул\b|"
    r"проспект[а-я]*|переул[а-я]*|шоссе|бульвар[а-я]*|набережн[а-я]*|площад[а-я]*|"
    r"республик[а-я]*|округ[а-я]*)", re.I)


def _morph():
    global _MORPH
    if _MORPH is None:
        _MORPH = pymorphy3.MorphAnalyzer()
    return _MORPH


@lru_cache(maxsize=50_000)
def _scores(word):
    """Разбор слова: (есть ли личное имя, балл фамилии/отчества, балл нарицательных).

    Помета Name (личное имя) стоит только у слов из словаря имён — её учитываем при
    любом балле: «Майя», «веру» основной вес отдают нарицательному значению, но это
    имена. Помету Surn pymorphy приписывает прилагательным («Страховой» как косвенный
    падеж от «Страхова»), поэтому для фамилий и отчеств нужен порог NAME_MIN.
    """
    parses = _morph().parse(word)
    given = any("Name" in p.tag.grammemes for p in parses)
    surn = sum(p.score for p in parses if {"Surn", "Patr"} & p.tag.grammemes)
    common = sum(p.score for p in parses
                 if p.is_known and not (_PROPER_TAGS & p.tag.grammemes))
    return given, surn, common


def _is_nameish(word):
    given, surn, _ = _scores(word)
    return given or surn >= NAME_MIN


def _is_common(word):
    """Словарное нарицательное слово, не являющееся именем."""
    given, surn, common = _scores(word)
    if given or surn >= NAME_MIN or common < COMMON_MIN:
        return False
    return not _SURNAME_SUFFIX.search(word)


def _is_short_noise(word):
    """Короткий токен (до 3 букв), не являющийся именем: «физ», «юр», «Оф»."""
    return len(word) <= 3 and not _is_nameish(word)


_LEFT_WORD = re.compile(r"([A-Za-zА-Яа-яЁё]+)[ \t]+$")
_RIGHT_WORD = re.compile(r"^[ \t]+([A-Za-zА-Яа-яЁё]+)")


def _next_to_name(text, start, end):
    """Стоит ли спан вплотную (через пробел) к слову-имени, отчеству или фамилии."""
    left = _LEFT_WORD.search(text[max(0, start - 40):start])
    right = _RIGHT_WORD.match(text[end:end + 40])
    return any(m and _is_nameish(m.group(1)) for m in (left, right))


def reject_reason(text, start, end):
    """Код правила, по которому спан PERSON отбрасывается, или None."""
    span = text[start:end]
    words = _WORD.findall(span)
    if not words:
        return "F1"
    # Инициал с точкой («А. Белых», «Белых В.Г.») — сильный признак имени: такой спан
    # морфологическими правилами не трогаем, иначе «А» (короткий токен) и «Белых»
    # (словарное прилагательное) выбросили бы настоящее ФИО. Адресный маркер (F5)
    # по-прежнему проверяется: адресные сокращения строчные, инициалы — заглавные.
    has_initial = bool(_INITIAL.search(span))
    # Одиночное слово вплотную к имени/отчеству/фамилии — часть длинного ФИО, которое
    # модель нашла не целиком: «Феодосию ВИКТОРОВИЧУ Самбуку» (найдено только
    # «Самбуку», а pymorphy знает его как напиток). Выбросив такой спан, мы открыли бы
    # всё ФИО. Соседи — только через пробел, без знаков препинания.
    if len(words) == 1 and _next_to_name(text, start, end):
        has_initial = True
    if not has_initial and len(words) == 1 and _is_short_noise(words[0]):
        return "F2"
    if not has_initial and len(words) == 1 and len(words[0]) > 3 and _is_common(words[0]):
        return "F3"
    # во фразе из нескольких слов короткие не-имена («физ. лицо») тоже нарицательные
    if not has_initial and len(words) >= 2 \
            and all(_is_common(w) or _is_short_noise(w) for w in words) \
            and not all(_is_short_noise(w) for w in words):
        return "F4"
    left = text[max(0, start - 18):start]
    if (_ABBR1_BEFORE.search(left) or _ABBRN_BEFORE.search(left) or _WORD_BEFORE.search(left)
            or _ABBR1_START.match(span) or _ABBRN_START.match(span)
            or _AFTER.match(text[end:end + 14])):
        return "F5"
    return None


def filter_person_results(text, results):
    """Убирает из результатов presidio ложные PERSON; остальные типы не трогает."""
    return [r for r in results
            if r.entity_type != "PERSON" or reject_reason(text, r.start, r.end) is None]
