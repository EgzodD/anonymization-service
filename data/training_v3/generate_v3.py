def frames_ok(templates, held_frames):
    kept, dropped = [], []
    for t in templates:
        t = t.strip().replace("\\n", "\n")
        if not t:
            continue
        fr = B.frames_of_template(re.sub(r"\{(city|street|org|title|brand|nsn|nsg)\}", "{X}", t))
        worst = max(B.jaccard(a, h) for a in fr for h in held_frames)
        (kept if worst < MAX_JACCARD else dropped).append((t, round(worst, 3)))
    return kept, dropped


def fill(template, rng):
    text, spans = "", []
    genders = []
    pos = 0
    for m in re.finditer(r"\{([^{}]+)\}", template):
        text += template[pos:m.start()]
        slot = m.group(1)
        if slot.startswith("P:"):
            _, case, group = slot.split(":")
            val, g = make_person(rng, case, group)
            genders.append(g)
            spans.append((len(text), len(text) + len(val)))
            text += val
        elif slot.startswith("g:"):
            a, b = slot[2:].split("|")
            text += a if rng.random() < 0.5 else b
        else:
            text += {"city": lambda: rng.choice(CITIES), "street": lambda: rng.choice(STREETS),
                     "org": lambda: rng.choice(ORGS), "title": lambda: rng.choice(TITLE_WORDS),
                     "brand": lambda: rng.choice(BRANDS),
                     "nsn": lambda: rng.choice(list(NOUN_SURN_COMMON)),
                     "nsg": lambda: NOUN_SURN_COMMON[rng.choice(list(NOUN_SURN_COMMON))].split()[3],
                     }[slot]()
        pos = m.end()
    text += template[pos:]
    if rng.random() < 0.3:
        text = text[:1].lower() + text[1:] if not spans or spans[0][0] > 0 else text
    return text, spans


def to_tokens(text, spans):
    toks, tags = [], []
    for t in tokenize(text):
        inside = [s for s in spans if s[0] <= t.start < s[1]]
        if inside:
            tags.append("I-PERSON" if toks and tags[-1] != "O" and inside[0][0] < t.start else "B-PERSON")
        else:
            tags.append("O")
        toks.append(t.text)
    return toks, tags


def main():
    clash = check_disjoint()
    assert not clash, f"лексиконы пересекаются с test_v2/dev_v2/регрессией: {clash}"
    held = set()
    for t in list(D.V2_TEMPLATES) + list(D.PII_TEMPLATES) + list(D.NEG_TEMPLATES):
        held |= B.frames_of_template(t)
    held |= {B.norm_frame(t) for t in list(D.V2_FIXED) + list(D.NEG_FIXED)}
    pos_t, pos_drop = frames_ok(POS_TEMPLATES, held)
    neg_t, neg_drop = frames_ok(NEG_TEMPLATES, held)
    rng = random.Random(SEED)
    rows = []
    for n, pool, src in ((N_POS, pos_t, "gen_pos"), (N_NEG, neg_t, "gen_neg")):
        for _ in range(n):
            text, spans = fill(rng.choice(pool)[0], rng)
            toks, tags = to_tokens(text, spans)
            assert tags.count("B-PERSON") == len(spans) or src == "gen_pos", text
            rows.append({"src": src, "tokens": toks, "tags": tags, "text": text})
    rng.shuffle(rows)
    with open(OUT, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    rep = {"pos_templates": len(pos_t), "neg_templates": len(neg_t),
           "dropped_too_similar": pos_drop + neg_drop,
           "max_jaccard_kept": max(j for _, j in pos_t + neg_t),
           "lexicon": {"male": len(MALE), "female": len(FEMALE), "patronymic_pairs": len(PATR),
                       "surnames": {k: len(v) for k, v in SURN.items()}, "cities": len(CITIES),
                       "streets": len(STREETS), "orgs": len(ORGS)},
           "examples": {"pos": N_POS, "neg": N_NEG}}
    with open(REPORT, "w", encoding="utf-8") as f:
        json.dump(rep, f, ensure_ascii=False, indent=2)
    print(json.dumps(rep, ensure_ascii=False, indent=2))


