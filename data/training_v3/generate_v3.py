def decline_surname(base, cls, gender, case):
    i = CASES.index(case)
    if cls == "soft":
        if gender == "femn":
            return base
        return base[:-1] + ["ь", "я", "ю", "я", "ем", "е"][i]
    if cls == "ov" and base.endswith("ой"):
        stem = base[:-2]
        if gender == "masc":
            return stem + ["ой", "ого", "ому", "ого", "им", "ом"][i]
        return stem + ["ая", "ой", "ой", "ую", "ой", "ой"][i]
    if cls == "sky" and base.endswith("ой"):
        return decline_surname(base, "ov", gender, case)
    if cls == "cons" and base[-1] in "жшчщц" and case == "ablt" and gender == "masc":
        return base + "ем"                       # Швецем, Бабичем (безударное окончание)
    return B.decline_surname(base, cls, gender, case)


def decline_first(word, gender, case):
    i = CASES.index(case)
    if gender == "masc" and word.endswith(("ь", "ай")):     # Игорь, Николай
        return word[:-1] + ["ь" if word.endswith("ь") else "й", "я", "ю", "я", "ем", "е"][i]
    form = B.decline_first_name(word, gender, case)
    # после г, к, х и шипящих пишется «и»: Ольги, Доминики (в test_v2 таких имён нет)
    if form.endswith("ы") and form[-2:-1] in "гкхжшчщ":
        form = form[:-1] + "и"
    return form


def decline_patr(word, gender, case):
    if word == "Ильич":
        return "Ильич" + ["", "а", "у", "а", "ом", "е"][CASES.index(case)]
    if word == "Ильинична":
        return "Ильинич" + ["на", "ны", "не", "ну", "ной", "не"][CASES.index(case)]
    return B.decline_patronymic(word, gender, case)


