def make_person(rng, case, group):
    gender = rng.choice(["masc", "femn"])
    first = rng.choice(MALE if gender == "masc" else FEMALE)
    patr = rng.choice(PATR)[0 if gender == "masc" else 1]
    cls = rng.choices(list(SURN), weights=[45, 12, 18, 18, 7])[0]
    surname = rng.choice(SURN[cls])
    if gender == "femn" and cls == "ov" and surname.endswith("ой"):
        cls = "ov"
    f, p, s = (decline_first(first, gender, case), decline_patr(patr, gender, case),
               decline_surname(surname, cls, gender, case))
    dot = rng.choice([".", ". "])
    ini = f"{first[0]}{dot}{patr[0]}."
    fmt = rng.choice(FORMATS[group])
    text = {"ИОФ": f"{f} {p} {s}", "ФИО": f"{s} {f} {p}", "ИФ": f"{f} {s}",
            "ФИ": f"{s} {f}", "ИО": f"{f} {p}", "ИнФ": f"{ini} {s}", "ФИн": f"{s} {ini}",
            "И": f, "Ф": s, "ФИ.": f"{s} {first[0]}.", "И.Ф": f"{first[0]}. {s}"}[fmt]
    r = rng.random()
    if r < LOWER_SHARE:
        text = text.lower()
    elif r < LOWER_SHARE + UPPER_SHARE:
        text = text.upper()
    return text, gender


