# коды/номера, которые ПДн НЕ являются и маскироваться НЕ должны (страж от
# избыточного маскирования — их значение обязано ОСТАТЬСЯ в тексте)
NON_PII_CASES = [
    ("Номер договора", "Номер договора: AG-2019-44182 действует.", "AG-2019-44182"),
    ("Код клиента", "Код клиента: RM-1991-2604 в профиле.", "RM-1991-2604"),
    ("Номер заказа", "Номер заказа: ORD-593184 отгружен.", "ORD-593184"),
    # 11-значный ID, начинающийся на 7/8, но НЕ мобильный (2-я цифра не 9) —
    # правило ru_phone_mobile9 не должно принять его за телефон
    ("11-зн ID не телефон", "Заказ номер 78123456789 в обработке.", "78123456789"),
    # голые 10-значные номера заказа/трека/договора — не ПДн (после снятия
    # встроенного presidio-телефона и context-free паспорта они не маскируются)
    ("трек-номер 10-зн", "Ваш трек-номер 1234567890 в пути.", "1234567890"),
    ("договор 10-зн", "Договор №12 34 567890 продлён.", "12 34 567890"),
]


@pytest.mark.parametrize("desc,text,must_mask", CASES,
                         ids=[c[0] for c in CASES])
def test_dirty_format_not_leaked(desc, text, must_mask):
    out = anonymize_text(text)["anonymized"]
    leaked = [v for v in must_mask if v in out]
    assert not leaked, f"[{desc}] утечка ПДн в выводе: {leaked}\nвывод: {out}"


@pytest.mark.parametrize("desc,text,keep", NON_PII_CASES,
                         ids=[c[0] for c in NON_PII_CASES])
def test_non_pii_not_over_masked(desc, text, keep):
    """Договорные/клиентские коды — не ПДн, должны остаться в тексте."""
    out = anonymize_text(text)["anonymized"]
    assert keep in out, f"[{desc}] не-ПДн код ошибочно замаскирован: {keep}\nвывод: {out}"


def test_anchor_does_not_cross_sentence_boundary():
    """Якорь ИНН/СНИЛС не должен маскировать число из СЛЕДУЮЩЕГО предложения.

    «нет ИНН. Мой заказ 5551234567 …» — число не ИНН; допускается лишь безопасное
    over-masking низкоприоритетными паттернами (телефон/паспорт 0.4), но НЕ метка
    INN/SNILS от якоря (score 0.9)."""
    res = anonymize_text("У меня нет ИНН. Мой заказ 5551234567 висит неделю.")
    anchored = {"INN", "SNILS"}
    hit = [e for e in res["entities_found"]
           if e["entity_type"] in anchored and e["value"].strip() == "5551234567"]
    assert not hit, f"якорь перепрыгнул границу предложения: {hit}"


# --- ФИО, приклеенное к соседнему слову без пробела (требует модель PERSON) -----
# Полное имя, где модель вернула спан (возможно с суб-токенного начала) —
# фильтр расширяет влево до границы слова, огрызок имени не остаётся.
GLUED_NAME_CASES = [
    ("спасибоАнна Кузнецова записала заявку", ["Анна", "Кузнецова"]),
    ("СпасибоИван Петров подтвердил", ["Иван", "Петров"]),
]

# Слово слито с ПЕРВЫМ именем без разделителя. Раньше помечено xfail: модель могла
# не отдать это имя. На боевой модели кейсы проходят (xpassed ещё с 02.09.2026),
# пометка снята 17.09.2026 — иначе потеря этих имён прогоном не ловилась бы
# (именно так при сравнении моделей 02.09 модель-кандидат теряла их незаметно).
GLUED_FIRST_NAME_CASES = [
    ("звонюИван Петров по делу", ["Иван"]),
    ("okИгорь Волков на связи", ["Игорь"]),
]


@pytest.mark.requires_model
@pytest.mark.parametrize("text,must_mask", GLUED_NAME_CASES,
                         ids=[c[0] for c in GLUED_NAME_CASES])
def test_glued_name_not_leaked(text, must_mask):
    """Имя, приклеенное к предыдущему слову, не должно утекать (spaCy-коллизия)."""
    out = anonymize_text(text)["anonymized"]
    leaked = [v for v in must_mask if v in out]
    assert not leaked, f"утечка имени при склейке: {leaked}\nвывод: {out}"


@pytest.mark.requires_model
@pytest.mark.parametrize("text,must_mask", GLUED_FIRST_NAME_CASES,
                         ids=[c[0] for c in GLUED_FIRST_NAME_CASES])
def test_glued_first_name_edge(text, must_mask):
    out = anonymize_text(text)["anonymized"]
    leaked = [v for v in must_mask if v in out]
    assert not leaked, f"утечка первого имени при склейке: {leaked}\nвывод: {out}"


# Фамилия, совпадающая с нарицательным словом (Мельник, Коваль, Кузнец, Горбач).
# Найдено 17.09.2026 пробой фильтра ложных PERSON: модель фамилию находила, а правило
# F3 («одно словарное нарицательное слово») её выбрасывало — фамилия утекала. dev-наборы
# таких фамилий не содержали, поэтому метрики этапа 2 дыру не показали.
NOUN_SURNAME_CASES = [
    ("Клиент Мельник просит перезвонить", "Мельник"),
    ("Сотрудник Коваль не ответил", "Коваль"),
    ("Добрый день, меня зовут Кузнец, жду ответа", "Кузнец"),
    ("Исполнитель по заявке Кузнец, телефон не указан", "Кузнец"),
    ("Ответ подготовил Горбач 12.09", "Горбач"),
    ("Подпись: Горбач", "Горбач"),
]


@pytest.mark.parametrize("text,surname", NOUN_SURNAME_CASES,
                         ids=[c[0] for c in NOUN_SURNAME_CASES])
def test_noun_surname_kept_by_filter(text, surname):
    """Фильтр не выбрасывает фамилию-нарицательное после слова-роли (без модели)."""
    from app.person_filters import reject_reason
    i = text.index(surname)
    assert reject_reason(text, i, i + len(surname)) is None


@pytest.mark.requires_model
@pytest.mark.parametrize("text,surname", NOUN_SURNAME_CASES,
                         ids=[c[0] for c in NOUN_SURNAME_CASES])
def test_noun_surname_not_leaked(text, surname):
    out = anonymize_text(text)["anonymized"]
    assert surname not in out, "утечка фамилии, совпадающей с нарицательным словом"
